def pe_version_strings(path: Path) -> dict[str, str]:
    """The version-resource strings of a Windows executable (empty dict elsewhere / none)."""
    if sys.platform != "win32":
        return {}
    import ctypes
    from ctypes import wintypes
    ver = ctypes.windll.version
    size = ver.GetFileVersionInfoSizeW(str(path), None)
    if not size:
        return {}
    buf = ctypes.create_string_buffer(size)
    if not ver.GetFileVersionInfoW(str(path), 0, size, buf):
        return {}
    ptr = ctypes.c_void_p()
    length = wintypes.UINT()
    out: dict[str, str] = {}
    langs = []
    if ver.VerQueryValueW(buf, "\\VarFileInfo\\Translation", ctypes.byref(ptr), ctypes.byref(length)) and length.value:
        arr = ctypes.cast(ptr, ctypes.POINTER(wintypes.WORD * (length.value // 2))).contents
        langs = [(arr[i], arr[i + 1]) for i in range(0, len(arr), 2)]
    langs = langs or [(0x0409, 0x04B0)]
    lang, cp = langs[0]
    for key in ("CompanyName", "FileDescription", "FileVersion", "ProductName", "ProductVersion",
                "OriginalFilename", "LegalCopyright"):
        sub = f"\\StringFileInfo\\{lang:04x}{cp:04x}\\{key}"
        if ver.VerQueryValueW(buf, sub, ctypes.byref(ptr), ctypes.byref(length)) and length.value:
            out[key] = ctypes.wstring_at(ptr, length.value).rstrip("\x00").strip()   # ISCC pads with spaces
    return out


def read_installer_manifest(path: Path) -> list[dict[str, str]]:
    """Rows of the manifest ISCC writes for ``OutputManifestFile`` (UTF-8, tab-separated, header)."""
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    if not lines:
        return []
    header = lines[0].split("\t")
    return [dict(zip(header, line.split("\t"), strict=False)) for line in lines[1:] if line.strip()]


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(8 * 1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def verify_installer_manifest(manifest: Path, dist: Path, *, check_hashes: bool = True) -> dict:
    """Prove that the compiled installer holds exactly the app folder, without running setup.

    The manifest lists every file ISCC compressed into setup with its source path, size and
    SHA-256 (computed by the compiler while it read the file). Every file of ``dist`` must
    appear once with the same size and hash, and nothing else may be in it. Paths are compared
    relative to the folder the manifest's entries share, so it does not matter how the build
    folder was spelled (8.3 names, a redirected AppData path). Returns a summary with
    ``ok`` and the first offending paths of each kind.
    """
    import time as _time
    t0 = _time.perf_counter()
    rows = read_installer_manifest(manifest)
    sources = [r.get("SourceFilename", "") for r in rows]
    if not sources:
        return {"ok": False, "files": 0, "reason": "empty manifest", "manifest": str(manifest)}
    base = os.path.commonpath([os.path.normcase(s) for s in sources]) if len(sources) > 1 \
        else os.path.normcase(os.path.dirname(sources[0]))
    packed: dict[str, dict[str, str]] = {}
    for src, row in zip(sources, rows, strict=True):
        packed[os.path.relpath(os.path.normcase(src), base).replace("\\", "/")] = row
    on_disk = {os.path.normcase(str(p.relative_to(dist))).replace("\\", "/"): p
               for p in dist.rglob("*") if p.is_file()}
    missing = sorted(set(on_disk) - set(packed))
    extra = sorted(set(packed) - set(on_disk))
    size_bad, hash_bad = [], []
    total = 0
    for rel in sorted(set(on_disk) & set(packed)):
        p, row = on_disk[rel], packed[rel]
        size = p.stat().st_size
        total += size
        if str(size) != row.get("OriginalSize", ""):
            size_bad.append(rel)
        elif check_hashes and row.get("SHA256Sum") and _sha256_file(p) != row["SHA256Sum"].lower():
            hash_bad.append(rel)
    return {
        "ok": not (missing or extra or size_bad or hash_bad),
        "manifest": str(manifest),
        "files": len(packed),
        "dist_files": len(on_disk),
        "bytes": total,
        "hashes_checked": bool(check_hashes),
        "missing": missing[:20], "n_missing": len(missing),
        "extra": extra[:20], "n_extra": len(extra),
        "size_mismatch": size_bad[:20], "hash_mismatch": hash_bad[:20],
        "seconds": round(_time.perf_counter() - t0, 1),
    }


def inspect_installer(path: Path, scan_bytes: int = 64 * 1024 * 1024) -> dict:
    """Facts about a compiled Inno Setup installer, without running it.

    Reads the PE version resource (which ``aerolume.iss`` fills from the package version) and
    looks for the ``Inno Setup Setup Data`` signature that precedes the compressed setup data,
    which proves the file is a complete Inno installer rather than a truncated copy.
    """
    info: dict = {"path": str(path), "bytes": path.stat().st_size, "version": pe_version_strings(path)}
    sig = b"Inno Setup Setup Data ("
    found = None
    with open(path, "rb") as f:
        chunk_size = 4 * 1024 * 1024
        offset = 0
        tail = b""
        while offset < min(scan_bytes, info["bytes"]):
            chunk = f.read(chunk_size)
            if not chunk:
                break
            data = tail + chunk
            i = data.find(sig)
            if i >= 0:
                end = data.find(b")", i)
                found = data[i:end + 1].decode("latin-1") if end > i else sig.decode()
                break
            tail = data[-len(sig):]
            offset += len(chunk)
    info["inno_signature"] = found
    info["sha256"] = _sha256_file(path)
    return info
