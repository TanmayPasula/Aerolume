def copy_app_files(dist_root: Path, repo: Path = REPO) -> list[str]:
    """Copy :data:`APP_FILES` and :data:`APP_DIRS` next to the executable; returns what was copied."""
    copied: list[str] = []
    for name in APP_FILES:
        src = repo / name
        if src.is_file():
            shutil.copy2(src, dist_root / name)
            copied.append(name)
    for folder, patterns in APP_DIRS.items():
        for pattern in patterns:
            for src in sorted((repo / folder).glob(pattern)):
                if src.is_file() and "__pycache__" not in src.parts:
                    dst = dist_root / folder / src.relative_to(repo / folder)
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dst)
                    copied.append(f"{folder}/{src.relative_to(repo / folder).as_posix()}")
    return copied


def copied_file_paths(repo: Path = REPO) -> set[str]:
    """Relative paths that :func:`copy_app_files` would copy from ``repo`` (same globs).

    These files are copied next to the executable after PyInstaller and nothing in the bundle
    is compiled from them, which is what makes ``build.py --refresh-docs`` sound: when a tree
    differs from a build's snapshot only in these paths, re-copying them gives the same folder a
    full rebuild would.
    """
    out = {name for name in APP_FILES if (repo / name).is_file()}
    for folder, patterns in APP_DIRS.items():
        for pattern in patterns:
            for src in (repo / folder).glob(pattern):
                if src.is_file() and "__pycache__" not in src.parts:
                    out.add(src.relative_to(repo).as_posix())
    return out


