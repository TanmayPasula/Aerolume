#: Packaging files that shape the built folder. ``smoke_test.py`` only reads the build, so
#: editing it does not make a build stale.
PACKAGING_INPUTS = ("aerolume.spec", "aerolume.iss", "buildlib.py", "build.py", "entry.py")


def source_files(repo: Path = REPO) -> list[tuple[str, Path]]:
    """Every file whose bytes end up in (or decide the contents of) the app folder.

    That is the whole ``src/aerolume`` package (code and data, as ``aerolume.spec`` collects
    it), ``pyproject.toml`` (dependencies decide the bundled metadata), the packaging inputs,
    the vendored licence texts (mfoil, ``packaging/licenses``) and the user-facing files
    ``copy_app_files`` copies. Bytecode and ``__pycache__`` are excluded: they are regenerated
    and never shipped. Returned as ``(posix path relative to repo, path)`` sorted by the
    relative path.
    """
    out: dict[str, Path] = {}

    def add(p: Path) -> None:
        if p.is_file() and "__pycache__" not in p.parts and p.suffix not in (".pyc", ".pyo"):
            out[p.relative_to(repo).as_posix()] = p

    pkg = repo / "src" / "aerolume"
    for p in pkg.rglob("*"):
        add(p)
    add(repo / "pyproject.toml")
    for name in PACKAGING_INPUTS:
        add(repo / "packaging" / name)
    add(repo / "third_party" / "mfoil" / "LICENSE")
    for p in (repo / "packaging" / "licenses").rglob("*"):    # vendored licence texts and notices
        add(p)
    for name in APP_FILES:
        add(repo / name)
    for folder, patterns in APP_DIRS.items():
        for pattern in patterns:
            for p in (repo / folder).glob(pattern):
                add(p)
    return sorted(out.items())


def source_fingerprint(repo: Path = REPO) -> dict:
    """SHA-256 over the paths and bytes of :func:`source_files`, plus the newest file.

    Two builds with the same fingerprint were made from byte-identical inputs. Line endings
    are hashed as they are on disk: the fingerprint compares builds of one working tree, not
    checkouts on different machines. ``newest`` names the most recently modified input, which
    is what a reader needs to see why a build is stale.
    """
    h = hashlib.sha256()
    total = 0
    newest_t, newest_f = 0.0, ""
    files = source_files(repo)
    for rel, p in files:
        data = p.read_bytes()
        total += len(data)
        h.update(rel.encode("utf-8") + b"\0" + str(len(data)).encode() + b"\0")
        h.update(data)
        mt = p.stat().st_mtime
        if mt > newest_t:
            newest_t, newest_f = mt, rel
    digest = h.hexdigest()
    import datetime as _dt
    newest = _dt.datetime.fromtimestamp(newest_t, _dt.UTC).astimezone().strftime("%Y-%m-%d %H:%M:%S") if newest_t else None
    return {"sha256": digest, "short": digest[:12], "files": len(files), "bytes": total,
            "newest": newest, "newest_file": newest_f}


def file_hashes(repo: Path = REPO) -> dict[str, str]:
    """SHA-256 of every :func:`source_files` entry, keyed by relative path.

    Used to say *which* inputs differ between a build's snapshot and the working tree; the
    single fingerprint only says *that* they differ.
    """
    return {rel: hashlib.sha256(p.read_bytes()).hexdigest() for rel, p in source_files(repo)}


def diff_sources(a: dict[str, str], b: dict[str, str]) -> dict[str, list[str]]:
    """Paths ``changed`` / ``added`` / ``removed`` going from hashes ``a`` to hashes ``b``."""
    return {"changed": sorted(k for k in a.keys() & b.keys() if a[k] != b[k]),
            "added": sorted(b.keys() - a.keys()),
            "removed": sorted(a.keys() - b.keys())}


#: Name of the frozen copy of the inputs inside a variant folder (see :func:`snapshot_sources`).
SNAPSHOT_DIR = "source"


class SnapshotError(RuntimeError):
    """The working tree never held still long enough to copy one consistent version of it."""


def _syntax_errors(root: Path) -> list[str]:
    """``.py`` inputs under ``root`` that do not compile - the signature of a half-written file."""
    bad = []
    for rel, p in source_files(root):
        if rel.endswith(".py"):
            try:
                compile(p.read_bytes(), rel, "exec", dont_inherit=True)
            except (SyntaxError, ValueError) as exc:
                bad.append(f"{rel}: {exc.__class__.__name__}: {exc}")
    return bad


def snapshot_sources(dest: Path, repo: Path = REPO, *, attempts: int = 6, settle_seconds: float = 5.0,
                     log=None) -> dict:
    """Copy every build input to ``dest`` once the tree holds still; returns the copy's fingerprint.

    Why: PyInstaller reads the package for about ten minutes, and on this project several people
    (and agents) edit the tree all day. Two builds in a row were thrown away because a file
    changed while PyInstaller was reading it, which leaves a folder that mixes two versions. The
    build therefore runs from a private copy: the copy cannot change under PyInstaller, and the
    app folder is, by construction, exactly the snapshot's fingerprint.

    A copy is accepted only if (1) the tree's fingerprint is the same before and after copying
    and equal to the copy's own - nothing changed while it was copied - and (2) every ``.py``
    file in it compiles, which catches an editor that had written half a file. Otherwise it
    waits ``settle_seconds`` and tries again, up to ``attempts`` times, then raises
    :class:`SnapshotError`. Modification times are preserved so "newest input" stays true.
    """
    log = log or (lambda _msg: None)
    last = ""
    for attempt in range(1, attempts + 1):
        before = source_fingerprint(repo)
        if dest.exists():
            shutil.rmtree(dest)
        for rel, src in source_files(repo):
            target = dest / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            try:
                shutil.copy2(src, target)
            except FileNotFoundError:       # deleted between listing and copying: tree is moving
                pass
        copy = source_fingerprint(dest)
        after = source_fingerprint(repo)
        if not (before["sha256"] == copy["sha256"] == after["sha256"]):
            last = (f"the tree changed while it was copied (newest input {after['newest_file']}, "
                    f"{after['newest']})")
        else:
            bad = _syntax_errors(dest)
            if not bad:
                copy.update(attempts=attempt, taken=time.strftime("%Y-%m-%d %H:%M:%S"))
                return copy
            last = f"{len(bad)} file(s) do not compile, e.g. {bad[0]}"
        log(f"snapshot attempt {attempt}/{attempts} rejected: {last}")
        if attempt < attempts:
            time.sleep(settle_seconds)
    raise SnapshotError(f"no consistent snapshot of {repo} after {attempts} attempts: {last}")


def verify_bundled_package(dist: Path, snapshot: Path) -> dict:
    """Compare the ``aerolume`` files inside the app folder with the snapshot, byte for byte.

    The spec ships the package as bytecode *and* source (``pyz+py``) and its data files at the
    same relative paths, so every non-test file of ``snapshot/src/aerolume`` must appear under
    ``_internal/aerolume`` with identical bytes. A mismatch would mean PyInstaller picked the
    package up from somewhere else (the editable install points at the live tree), which is
    exactly the mixing the snapshot exists to prevent.
    """
    pkg = snapshot / "src" / "aerolume"
    roots = [dist / "_internal" / "aerolume", dist / "aerolume"]
    bundled = next((r for r in roots if r.is_dir()), roots[0])
    same, differ, missing, skipped, scripts = 0, [], [], 0, []
    for p in sorted(pkg.rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts or p.suffix in (".pyc", ".pyo"):
            continue
        rel = p.relative_to(pkg)
        if not not_a_test_module("aerolume." + ".".join(rel.with_suffix("").parts)):
            skipped += 1
            continue
        if p.suffix == ".py" and not all((pkg / d / "__init__.py").is_file()
                                         for d in (Path(*rel.parts[:i]) for i in range(1, len(rel.parts)))):
            # A script outside the package tree (e.g. a developer's font-subsetting helper in a
            # resources folder) is neither a module nor package data: PyInstaller rightly skips it.
            scripts.append(rel.as_posix())
            continue
        q = bundled / rel
        if not q.is_file():
            missing.append(rel.as_posix())
        elif q.read_bytes() != p.read_bytes():
            differ.append(rel.as_posix())
        else:
            same += 1
    return {"ok": not differ and not missing, "identical": same, "differ": differ, "missing": missing,
            "skipped_tests": skipped, "skipped_scripts": scripts, "bundled_root": str(bundled)}


class RefreshRefused(RuntimeError):
    """``--refresh-docs`` cannot stand in for a full build (code changed, or no usable build)."""


def refresh_copied_files(variant_dir: Path, repo: Path = REPO, *, log=None, **snapshot_kw) -> dict:
    """Bring a built folder up to date when only copied files (docs, README...) changed.

    Why this exists: the release build's own measurements belong in ``docs/install.md``, which
    the app ships, so writing them down makes the build stale. A second 15-minute PyInstaller
    run would then be needed for a byte that PyInstaller never reads. Instead this takes a new
    snapshot, proves that every path differing from the build's snapshot is one that
    :func:`copy_app_files` copies (never a bundled module, ``pyproject.toml`` or a packaging
    script), re-copies those files into ``dist``, swaps the snapshot and rewrites
    ``build-info.json`` with the new fingerprint plus a ``docs_refreshed`` record of what
    changed. The result is the folder a full build of the new snapshot would produce; the caller
    then re-runs the smoke test and recompiles the installer. Raises :class:`RefreshRefused`
    (leaving everything as it was) when a full build is needed.
    """
    log = log or (lambda _msg: None)
    dist = variant_dir / "dist" / APP_NAME
    snap = variant_dir / SNAPSHOT_DIR
    info = read_json(dist / "build-info.json") or {}
    if not (dist / GUI_EXE).is_file() or not info.get("source_sha256"):
        raise RefreshRefused(f"{dist} holds no fingerprinted build to refresh; run a full build")
    if not snap.is_dir() or source_fingerprint(snap)["sha256"] != info["source_sha256"]:
        raise RefreshRefused(f"{snap} is not the snapshot {dist.name} was built from; run a full build")
    if smoke_result_for(read_json(variant_dir / "build-report.json") or {}, info) == "failed":
        raise RefreshRefused("that folder failed its smoke test; run a full build")
    new_dir = variant_dir / (SNAPSHOT_DIR + ".new")
    try:
        new = snapshot_sources(new_dir, repo, log=log, **snapshot_kw)
        old_hashes, new_hashes = file_hashes(snap), file_hashes(new_dir)
        diff = diff_sources(old_hashes, new_hashes)
        names = diff["changed"] + diff["added"] + diff["removed"]
        copied = copied_file_paths(snap) | copied_file_paths(new_dir)
        bundled = sorted(n for n in names if n not in copied)
        if bundled:
            more = f" and {len(bundled) - 6} more" if len(bundled) > 6 else ""
            raise RefreshRefused("files that the build compiles or bundles changed since its snapshot: "
                                 + ", ".join(bundled[:6]) + more + "; run a full build")
    except BaseException:
        shutil.rmtree(new_dir, ignore_errors=True)
        raise
    if not names:
        shutil.rmtree(new_dir, ignore_errors=True)
        return {"changed": [], "added": [], "removed": [], "source": None}
    for rel in diff["removed"]:
        with contextlib.suppress(FileNotFoundError):
            (dist / rel).unlink()
    copy_app_files(dist, new_dir)
    shutil.rmtree(snap)
    new_dir.rename(snap)
    record = {"from_sha256": info["source_sha256"], "at": time.strftime("%Y-%m-%d %H:%M:%S"),
              "changed": diff["changed"], "added": diff["added"], "removed": diff["removed"]}
    info.update(source_sha256=new["sha256"], source_files=new["files"], source_newest=new["newest"],
                source_newest_file=new["newest_file"], source_snapshot_taken=new.get("taken"),
                docs_refreshed=[*info.get("docs_refreshed", []), record])
    (dist / "build-info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
    log(f"re-copied {len(names)} file(s) into {dist}: " + ", ".join(names[:6]) + (" ..." if len(names) > 6 else ""))
    return {**{k: diff[k] for k in ("changed", "added", "removed")}, "source": new, "build_info": info}


def read_json(path: Path) -> dict | None:
    """A JSON object from ``path``, or ``None`` if it is missing, unreadable or not an object."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def build_status(variant_dir: Path, *, version: str | None = None, fingerprint: dict | None = None,
                 repo: Path = REPO) -> dict:
    """Is the build in ``variant_dir`` current for this source tree? Never guesses "yes".

    States of the app folder (``dist``):

    * ``missing`` - no ``Aerolume.exe``;
    * ``unverifiable`` - built before builds recorded a source fingerprint, so nothing proves
      which sources it contains (treated as not current);
    * ``stale`` - a different version, a different source fingerprint, or the sources changed
      while PyInstaller was reading them;
    * ``failed`` - ``build-report.json`` records that this very folder failed its smoke test
      (the 24 Oct build did: its bundled metadata said 0.1.0). The folder is complete and
      matches its sources, so without this state ``--status --skip-installer`` called it
      current;
    * ``untested`` - the report records that the smoke test was skipped for this folder;
    * ``current`` - same version and byte-identical inputs, and not known to have failed.

    Installers are checked the same way through ``build-report.json`` (which records the
    fingerprint of the folder each installer was compiled from); one is ``current`` only when
    its fingerprint and version match and the app folder is current. ``current`` in the result
    is True only when the app folder is current; ``installer_current`` adds the installer.
    """
    version = version or read_version(repo)
    fp = fingerprint or source_fingerprint(repo)
    dist = variant_dir / "dist" / APP_NAME
    info = read_json(dist / "build-info.json") or {}
    report = read_json(variant_dir / "build-report.json") or {}
    reasons: list[str] = []
    smoke_verdict = None
    if not (dist / GUI_EXE).is_file():
        state = "missing"
        reasons.append(f"no {GUI_EXE} in {dist}")
    else:
        smoke_verdict = smoke_result_for(report, info)
        if smoke_verdict == "failed":
            reasons.append("its smoke test failed: " + smoke_failure_summary(report.get("smoke") or {}))
        elif smoke_verdict == "skipped":
            reasons.append("it was never smoke-tested (built with --skip-smoke)")
        built_hash = info.get("source_sha256")
        if info.get("version") != version:
            reasons.append(f"built as version {info.get('version') or '?'}, the source is {version}")
        if not built_hash:
            reasons.append("the build records no source fingerprint (made before fingerprints were added)")
        elif built_hash != fp["sha256"]:
            reasons.append(f"source fingerprint {built_hash[:12]} differs from the tree's {fp['short']} "
                           f"(newest input: {fp['newest_file']}, {fp['newest']})")
            moved = _changes_since_snapshot(variant_dir, built_hash, repo)
            if moved:
                reasons.append(moved)
        if info.get("source_changed_during_build"):
            reasons.append("the sources changed while the build was reading them")
        newer = _inputs_modified_after(info.get("built"), repo)
        if not built_hash and newer:
            # A build without a fingerprint can still be proven old: inputs changed after it.
            reasons.append(f"{len(newer)} source files were modified after it was built "
                           f"(newest: {fp['newest_file']}, {fp['newest']})")
        smoke_reasons = 1 if smoke_verdict in ("failed", "skipped") else 0
        if smoke_verdict == "failed":
            state = "failed"
        elif len(reasons) == smoke_reasons and smoke_verdict == "skipped":
            state = "untested"
        elif not reasons:
            state = "current"
        elif not built_hash and info.get("version") == version and not newer and not smoke_reasons:
            state = "unverifiable"
        else:
            state = "stale"
    installers = []
    rep_inst = report.get("installer") or {}
    for setup in sorted((variant_dir / "installer").glob(f"{APP_NAME}-*-setup.exe")):
        why: list[str] = []
        same_file = Path(rep_inst.get("path", "")).name.lower() == setup.name.lower()
        inst_hash = rep_inst.get("source_sha256") if same_file else None
        if not setup.name.startswith(f"{APP_NAME}-{version}-"):
            why.append("named for another version")
        if not inst_hash:
            why.append("no source fingerprint recorded for this installer")
        elif inst_hash != fp["sha256"]:
            why.append("compiled from other sources")
        if same_file and rep_inst.get("bytes") not in (None, setup.stat().st_size):
            why.append("size differs from the build report (replaced or truncated)")
        if state == "failed":
            why.append("the app folder it would install failed its smoke test")
        elif state != "current":
            why.append("the app folder is not current")
        installers.append({"path": str(setup), "real_path": str(real_location(setup)),
                           "bytes": setup.stat().st_size,
                           "modified": _fmt_mtime(setup), "current": not why, "reasons": why})
    return {
        "variant_dir": str(variant_dir), "real_variant_dir": str(real_location(variant_dir)),
        "state": state, "current": state == "current", "reasons": reasons,
        "version": version, "built_version": info.get("version"), "built": info.get("built"),
        "built_source": (info.get("source_sha256") or "")[:12] or None, "source": fp["short"],
        "installers": installers,
        "installer_current": state == "current" and any(i["current"] for i in installers),
    }


def smoke_result_for(report: dict, info: dict) -> str | None:
    """``"passed"``/``"failed"``/``"skipped"`` if ``report`` holds the smoke result of the folder
    described by ``info`` (its ``build-info.json``), else ``None``.

    A report belongs to a folder only when its ``build_info`` names the same source fingerprint
    and build time: after a crashed rebuild, an old report must not vouch for (or condemn) a
    folder it never tested. Reports from before smoke results were recorded yield ``None``.
    """
    smoke = report.get("smoke")
    rep_info = report.get("build_info") or {}
    if not isinstance(smoke, dict) or not info:
        return None
    if (rep_info.get("source_sha256"), rep_info.get("built")) != (info.get("source_sha256"), info.get("built")):
        return None
    if smoke.get("skipped"):
        return "skipped"
    return "passed" if smoke.get("ok") is True else "failed"


def smoke_failure_summary(smoke: dict, limit: int = 3) -> str:
    """The failed smoke checks in one line, e.g. ``selftest (first launch): package metadata``."""
    parts = []
    for check in smoke.get("checks") or []:
        if check.get("ok"):
            continue
        inner = [c.get("name", "?") for c in ((check.get("report") or {}).get("checks") or []) if not c.get("ok")]
        parts.append(f"{check.get('name', '?')}" + (f" ({', '.join(inner)})" if inner else ""))
    if not parts:
        return "no passing result recorded"
    more = f" and {len(parts) - limit} more" if len(parts) > limit else ""
    return "; ".join(parts[:limit]) + more


def _changes_since_snapshot(variant_dir: Path, built_hash: str, repo: Path = REPO, show: int = 6) -> str | None:
    """Which inputs changed since the build's snapshot, in one line (None without a snapshot).

    A build from a snapshot is internally consistent; when it is "stale" the useful question
    is how far the tree has moved on - a one-line doc edit and a solver rewrite read the same
    in a fingerprint.
    """
    snap = variant_dir / SNAPSHOT_DIR
    if not snap.is_dir():
        return None
    try:
        if source_fingerprint(snap)["sha256"] != built_hash:
            return None
        d = diff_sources(file_hashes(snap), file_hashes(repo))
    except OSError:
        return None
    names = d["changed"] + d["added"] + d["removed"]
    if not names:
        return None
    more = f" and {len(names) - show} more" if len(names) > show else ""
    return (f"since its snapshot the tree changed {len(d['changed'])}, added {len(d['added'])} and removed "
            f"{len(d['removed'])} input(s): " + ", ".join(names[:show]) + more)


def _inputs_modified_after(built: str | None, repo: Path = REPO) -> list[str]:
    """Inputs whose modification time is later than ``built`` (``YYYY-mm-dd HH:MM:SS``, local)."""
    if not built:
        return []
    import datetime as _dt
    try:
        t = _dt.datetime.strptime(built, "%Y-%m-%d %H:%M:%S").astimezone().timestamp()
    except ValueError:
        return []
    return [rel for rel, p in source_files(repo) if p.stat().st_mtime > t + 1.0]


def _fmt_mtime(path: Path) -> str:
    import datetime as _dt
    return _dt.datetime.fromtimestamp(path.stat().st_mtime, _dt.UTC).astimezone().strftime("%Y-%m-%d %H:%M:%S")


def find_iscc() -> Path | None:
    """The Inno Setup 6 command-line compiler: ``AEROLUME_ISCC``, the per-user default, PATH."""
    env = os.environ.get("AEROLUME_ISCC")
    candidates = [Path(env)] if env else []
    candidates += [DEFAULT_ISCC, Path(os.environ.get("ProgramFiles(x86)", "")) / "Inno Setup 6" / "ISCC.exe",
                   Path(os.environ.get("ProgramFiles", "")) / "Inno Setup 6" / "ISCC.exe"]
    which = shutil.which("ISCC")
    if which:
        candidates.append(Path(which))
    for c in candidates:
        if c and c.is_file():
            return c
    return None


