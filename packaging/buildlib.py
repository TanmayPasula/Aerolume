def _render_rgba(svg: Path, size: int) -> bytes:
    """The SVG rendered at ``size`` px as straight (non-premultiplied) BGRA rows, top-down."""
    from PySide6.QtCore import QRectF, Qt
    from PySide6.QtGui import QGuiApplication, QImage, QPainter
    from PySide6.QtSvg import QSvgRenderer
    if QGuiApplication.instance() is None:
        os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
        _render_rgba.app = QGuiApplication([sys.argv[0] if sys.argv else "buildlib"])  # type: ignore[attr-defined]
    ren = QSvgRenderer(str(svg))
    if not ren.isValid():
        raise ValueError(f"cannot render {svg}")
    img = QImage(size, size, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    ren.render(p, QRectF(0, 0, size, size))
    p.end()
    img = img.convertToFormat(QImage.Format.Format_ARGB32)       # BGRA bytes on little-endian
    return bytes(img.constBits())[: size * size * 4]


def _png_bytes(svg: Path, size: int) -> bytes:
    from PySide6.QtCore import QBuffer, QByteArray, QIODevice
    from PySide6.QtGui import QImage
    raw = _render_rgba(svg, size)
    img = QImage(raw, size, size, size * 4, QImage.Format.Format_ARGB32)
    ba = QByteArray()
    buf = QBuffer(ba)
    buf.open(QIODevice.OpenModeFlag.WriteOnly)
    img.save(buf, "PNG")
    buf.close()
    return bytes(ba.data())


def _dib_bytes(bgra: bytes, size: int) -> bytes:
    """A 32-bit ICO bitmap entry: BITMAPINFOHEADER (double height), bottom-up pixels, AND mask."""
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    stride = size * 4
    rows = [bgra[r * stride:(r + 1) * stride] for r in range(size)]
    pixels = b"".join(reversed(rows))
    mask_stride = ((size + 31) // 32) * 4
    mask = bytearray()
    for r in reversed(range(size)):
        row = bytearray(mask_stride)
        for c in range(size):
            if bgra[r * stride + c * 4 + 3] == 0:          # fully transparent -> masked
                row[c // 8] |= 0x80 >> (c % 8)
        mask += row
    return header + pixels + bytes(mask)


def make_ico(svg: Path, out: Path, sizes: Iterable[int] = ICON_SIZES) -> Path:
    """Write a multi-resolution Windows icon rendered from ``svg``.

    Sizes up to 48 px are stored as classic 32-bit bitmaps (what Explorer, the taskbar and the
    installer's small icons read most reliably); 64 px and up as PNG, which keeps the file
    small. The single source of truth stays ``aerolume/app/resources/aerolume.svg``.
    """
    sizes = sorted({int(s) for s in sizes})
    images = []
    for s in sizes:
        data = _dib_bytes(_render_rgba(svg, s), s) if s <= 48 else _png_bytes(svg, s)
        images.append((s, data))
    head = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    entries = b""
    blobs = b""
    for s, data in images:
        dim = 0 if s >= 256 else s
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset + len(blobs))
        blobs += data
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(head + entries + blobs)
    return out


def read_ico_sizes(path: Path) -> list[int]:
    """The image sizes stored in an ``.ico`` file (for tests and the build report)."""
    data = path.read_bytes()
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 1:
        raise ValueError(f"{path} is not an icon file")
    sizes = []
    for i in range(count):
        w = data[6 + 16 * i]
        sizes.append(256 if w == 0 else w)
    return sizes


#: Apple icon-family entries, all PNG: (OSType, pixel size). The set ``iconutil`` writes for a full
#: ``.iconset`` (16 to 512 pt at 1x and 2x); macOS 10.7 and later read PNG data in every one of them.
ICNS_ENTRIES = (("icp4", 16), ("icp5", 32), ("ic11", 32), ("icp6", 64), ("ic12", 64), ("ic07", 128),
                ("ic13", 256), ("ic08", 256), ("ic14", 512), ("ic09", 512), ("ic10", 1024))


def make_icns(svg: Path, out: Path, entries: Iterable[tuple[str, int]] = ICNS_ENTRIES) -> Path:
    """Write a macOS ``.icns`` icon family rendered from ``svg`` (for the ``.app`` bundle).

    The format is a big-endian container: the magic ``icns`` and the total length, then one
    record per image (its four-character type, its own length including that 8-byte header, and
    the PNG bytes). Writing it here, from the same SVG as the Windows ``.ico``, means a Mac build
    needs neither ``iconutil`` nor a second hand-made icon, and the two platforms cannot drift.
    """
    pngs: dict[int, bytes] = {}
    body = b""
    for ostype, size in entries:
        if len(ostype) != 4:
            raise ValueError(f"ICNS type must be four characters, not {ostype!r}")
        data = pngs.setdefault(size, _png_bytes(svg, size))
        body += ostype.encode("ascii") + struct.pack(">I", 8 + len(data)) + data
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(b"icns" + struct.pack(">I", 8 + len(body)) + body)
    return out


def read_icns_entries(path: Path) -> list[tuple[str, int]]:
    """(type, pixel width) of every image in an ``.icns`` file, read from the PNG headers (for tests)."""
    data = path.read_bytes()
    if data[:4] != b"icns" or struct.unpack_from(">I", data, 4)[0] != len(data):
        raise ValueError(f"{path} is not an icns file")
    out, pos = [], 8
    while pos < len(data):
        ostype = data[pos:pos + 4].decode("ascii")
        length = struct.unpack_from(">I", data, pos + 4)[0]
        png = data[pos + 8:pos + length]
        if png[:8] != b"\x89PNG\r\n\x1a\n":
            raise ValueError(f"{ostype} in {path} is not PNG data")
        out.append((ostype, struct.unpack_from(">I", png, 16)[0]))
        pos += length
    return out


def ensure_generated(gen_dir: Path, variant: str, version: str | None = None,
                     repo: Path = REPO) -> dict[str, Path]:
    """Create the icons (``.ico``, and ``.icns`` for a macOS bundle) and both version resources in
    ``gen_dir`` (idempotent per version, variant and icon source)."""
    version = version or read_version(repo)
    gen_dir.mkdir(parents=True, exist_ok=True)
    icon = gen_dir / "aerolume.ico"
    svg = repo / "src" / "aerolume" / "app" / "resources" / "aerolume.svg"
    stamp = gen_dir / "stamp.json"
    key = {"version": version, "variant": variant, "svg": hashlib.sha256(svg.read_bytes()).hexdigest()}
    current = None
    with contextlib.suppress(OSError, ValueError):
        current = json.loads(stamp.read_text(encoding="utf-8"))
    files = {"icon": icon, "icns": gen_dir / "aerolume.icns", "version_gui": gen_dir / "version_gui.txt",
             "version_cli": gen_dir / "version_cli.txt"}
    if current == key and all(p.exists() for p in files.values()):
        return files
    make_ico(svg, icon)
    make_icns(svg, files["icns"])
    files["version_gui"].write_text(version_resource(version, variant, exe_name=GUI_EXE,
                                                      description="Aerolume aerodynamics studio"), encoding="utf-8")
    files["version_cli"].write_text(version_resource(version, variant, exe_name=CLI_EXE,
                                                      description="Aerolume command line"), encoding="utf-8")
    stamp.write_text(json.dumps(key), encoding="utf-8")
    return files


