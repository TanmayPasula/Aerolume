def project_requirements(extras: Iterable[str] = ("ai",), repo: Path = REPO) -> list[str]:
    """Aerolume's own requirements read from ``pyproject.toml`` (dependencies + ``extras``).

    Read from the source, not from the installed metadata: an editable install keeps the
    ``Requires-Dist`` of the day it was installed, which goes stale when a dependency is added
    (on the development machine it still lacked ``vtk`` and the ``ai`` extra).
    """
    import tomllib
    project = tomllib.loads((repo / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    reqs = list(project.get("dependencies", []))
    for extra in extras:
        reqs += project.get("optional-dependencies", {}).get(extra, [])
    return reqs


def write_dist_info(out_parent: Path, repo: Path = REPO) -> Path:
    """Write ``aerolume-<version>.dist-info`` for the frozen app from ``pyproject.toml``.

    The editable install's own ``.dist-info`` is frozen at the day ``pip install -e`` ran: on
    the development machine it still says the version and dependencies of 0.1.0 and its
    ``direct_url.json`` names the developer's OneDrive folder. Copying it would make
    ``importlib.metadata`` in the app (the Help menu's project links, report provenance)
    disagree with ``aerolume.__version__``. So the metadata the app ships is generated from the
    same sources as the code: name, version, summary, licence, project URLs and requirements.
    """
    import tomllib
    project = tomllib.loads((repo / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    version = read_version(repo)
    out_parent.mkdir(parents=True, exist_ok=True)
    for old in out_parent.glob("aerolume-*.dist-info"):
        shutil.rmtree(old)
    folder = out_parent / f"aerolume-{version}.dist-info"
    folder.mkdir()
    lines = ["Metadata-Version: 2.4", "Name: aerolume", f"Version: {version}"]
    if project.get("description"):
        lines.append(f"Summary: {project['description']}")
    for author in project.get("authors", []):
        if author.get("name"):
            lines.append(f"Author: {author['name']}")
    if isinstance(project.get("license"), str):
        lines.append(f"License-Expression: {project['license']}")
    if project.get("keywords"):
        lines.append("Keywords: " + ",".join(project["keywords"]))
    lines += [f"Classifier: {c}" for c in project.get("classifiers", [])]
    if project.get("requires-python"):
        lines.append(f"Requires-Python: {project['requires-python']}")
    lines += [f"Project-URL: {label}, {url}" for label, url in project.get("urls", {}).items()]
    lines += [f"Requires-Dist: {r}" for r in project.get("dependencies", [])]
    for extra, reqs in project.get("optional-dependencies", {}).items():
        lines.append(f"Provides-Extra: {extra}")
        lines += [f'Requires-Dist: {r}; extra == "{extra}"' for r in reqs]
    (folder / "METADATA").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (folder / "top_level.txt").write_text("aerolume\n", encoding="utf-8")
    (folder / "INSTALLER").write_text("aerolume-packaging\n", encoding="utf-8")
    return folder


def dependency_closure(extras: Iterable[str] = ("ai",), repo: Path = REPO) -> list[str]:
    """Installed distributions Aerolume (with ``extras``) needs, transitively, as installed.

    The frozen app has no ``site-packages``, so ``importlib.metadata.version("vtk")`` fails
    unless the ``.dist-info`` folders are bundled - and several libraries (and
    ``aerolume-cli doctor``) look themselves up that way. The spec copies the metadata of
    exactly this set: the declared dependency tree, not whatever else is in the venv.
    """
    from importlib import metadata

    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    seen: dict[str, str] = {}
    todo: list[tuple[str, tuple[str, ...]]] = [("aerolume", ())]
    first = True
    while todo:
        name, wanted = todo.pop()
        key = canonicalize_name(name)
        if key in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = dist.metadata["Name"]
        requires = project_requirements(extras, repo) if first else (dist.requires or [])
        first = False
        for raw in requires:
            req = Requirement(raw)
            if req.marker is not None:
                envs = [{"extra": e} for e in wanted] or [{"extra": ""}]
                if not any(req.marker.evaluate(env) for env in envs):
                    continue
            todo.append((req.name, tuple(req.extras)))
    return sorted(seen.values(), key=str.lower)


def not_a_test_module(name: str) -> bool:
    """Filter for ``collect_submodules``: drop test suites, which only cost size."""
    parts = name.split(".")
    return not any(p in ("tests", "test", "testing", "_testutils", "conftest") for p in parts[1:])


