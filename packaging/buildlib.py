def onedrive_roots() -> list[Path]:
    """Folders synchronised by OneDrive (from the variables OneDrive sets for the user)."""
    roots = []
    for var in ("OneDrive", "OneDriveConsumer", "OneDriveCommercial"):
        v = os.environ.get(var)
        if v:
            roots.append(Path(v))
    return roots


def is_under_onedrive(path: Path) -> bool:
    """True if ``path`` is inside a OneDrive folder (where build outputs get locked mid-write)."""
    resolved = path.resolve()
    p = os.path.normcase(str(resolved))
    for r in onedrive_roots():
        root = os.path.normcase(str(r.resolve()))
        if p == root or p.startswith(root.rstrip("\\/") + os.sep):
            return True
    # Without the variables (another user's shell, a service), fall back to the folder names
    # OneDrive uses: "OneDrive" (personal) and "OneDrive - <organisation>" (work or school).
    return any(part.lower() == "onedrive" or part.lower().startswith("onedrive - ") for part in resolved.parts)


#: Environment variable that overrides :func:`default_build_root` (``--build-root`` wins over both).
BUILD_ROOT_ENV = "AEROLUME_BUILD_ROOT"


def default_build_root() -> Path:
    """``%USERPROFILE%\\aerolume-build``, or ``AEROLUME_BUILD_ROOT`` when that is set.

    Why the profile folder and not ``%LOCALAPPDATA%``: a process started by a packaged (MSIX)
    Windows app - the Claude desktop app, some IDEs and terminals - has new folders under
    ``AppData`` silently redirected to ``AppData\\Local\\Packages\\<app>\\LocalCache``. The
    build then "succeeds" into a folder that Explorer and every other program cannot see at the
    path the log printed. Only ``AppData`` is virtualised, so the profile root is seen
    identically by every process. It is also outside OneDrive (which syncs Desktop and
    Documents, not the profile root) and is not roamed.
    """
    env = os.environ.get(BUILD_ROOT_ENV)
    if env:
        return Path(env)
    home = os.environ.get("USERPROFILE") or str(Path.home())
    return Path(home) / "aerolume-build"


def legacy_build_roots() -> list[Path]:
    """Build roots used by earlier versions of ``build.py`` (``%LOCALAPPDATA%\\aerolume-build``).

    ``build.py --status`` reports them so an old installer left there is never mistaken for
    the current one.
    """
    base = os.environ.get("LOCALAPPDATA") or str(Path.home() / "AppData" / "Local")
    return [Path(base) / "aerolume-build"]


def real_location(path: Path) -> Path:
    """Where ``path`` really is on disk for other programs (follows MSIX redirection and links)."""
    try:
        return path.resolve()
    except OSError:
        return path.absolute()


def redirected(path: Path) -> Path | None:
    """The real folder when Windows redirects ``path`` for this process, else ``None``.

    Inside a packaged app ``Path.resolve`` returns the private ``...\\Packages\\<app>\\
    LocalCache\\...`` copy of an ``AppData`` path, which is how the redirection is detected.
    Comparison is case-insensitive and ignores 8.3 spellings that ``resolve`` expands.
    """
    real = real_location(path)
    spelled = path.absolute()
    if os.path.normcase(str(real)) == os.path.normcase(str(spelled)):
        return None
    with contextlib.suppress(OSError):
        if os.path.normcase(os.path.realpath(os.path.dirname(spelled))) == \
                os.path.normcase(str(real.parent)) and real.name.lower() == spelled.name.lower():
            return None     # only the spelling differs (8.3 name, drive letter case)
    return real


def is_msix_private(path: Path) -> bool:
    """True if ``path`` is inside a packaged app's private ``AppData\\Local\\Packages`` store."""
    parts = [p.lower() for p in real_location(path).parts]       # ...\Packages\<app>\LocalCache\...
    return any(a == "packages" and b == "localcache" for a, b in zip(parts, parts[2:], strict=False))


