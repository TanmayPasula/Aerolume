#: packaging/licenses/qt) with their SHA-256 values, which a test pins.
UPSTREAM_LICENSE_SUMS = VENDORED_LICENSES / "UPSTREAM.sha256"


@dataclass
class BundledDistribution:
    """One third-party distribution found in the bundle, for ``licenses/README.txt``."""

    name: str
    version: str
    license: str
    files: list[str]


def _licence_subpath(posix: str) -> str:
    """Where a distribution's licence file goes below ``licenses/<name>/``.

    A file inside the ``.dist-info`` folder keeps its path below that folder (a leading
    ``licenses/`` dropped). Nested third-party licences therefore keep their folders: PyTorch
    ships 95 of them as ``licenses/third_party/<project>/LICENSE[.txt]``. Flattening them to
    their file names, as builds before 0.1.0 did, left one ``LICENSE`` and one ``LICENSE.txt``
    and lost the rest, CUTLASS, cuDNN frontend and NVTX among them. A file at the top of a
    package (``numpy/LICENSE.txt``) keeps its name.
    """
    if ".dist-info/" in posix:
        rel = posix.split(".dist-info/", 1)[1]
        return rel.removeprefix("licenses/") or Path(posix).name
    return Path(posix).name


def _file_facts(path: Path) -> str:
    """Two indented lines for a notice: what the file says it is, and its copyright line."""
    v = pe_version_strings(path)
    if not v:
        return "    (the file carries no version resource)"
    what = v.get("FileDescription") or v.get("ProductName") or ""
    ver = v.get("FileVersion") or v.get("ProductVersion") or ""
    first = "; ".join(x for x in (what, f"file version {ver}" if ver else "") if x)
    lines = [f"    {first}"] if first else []
    if v.get("LegalCopyright"):
        lines.append(f"    {v['LegalCopyright']}")
    return "\n".join(lines) or "    (the file's version resource names no product)"


def _fill(template: str, **values: str) -> str:
    """``{name}`` placeholders of a vendored notice, replaced (no other braces are touched)."""
    for key, value in values.items():
        template = template.replace("{" + key + "}", value)
    return template


def _runtime_notice(dist_root: Path, out: Path, template: Path, pattern: re.Pattern[str], **values: str) -> list[str]:
    """Write ``out`` = the vendored notice + every file of the bundle matching ``pattern`` with its
    recorded facts; returns the files listed (relative to the bundle), or [] when none is bundled."""
    hits = sorted((p for p in dist_root.rglob("*.dll") if pattern.match(p.name)),
                  key=lambda p: p.relative_to(dist_root).as_posix().lower())
    if not hits:
        return []
    rels = [p.relative_to(dist_root).as_posix() for p in hits]
    body = [_fill(template.read_text(encoding="utf-8"), **values).rstrip("\n"), ""]
    for p, rel in zip(hits, rels, strict=True):
        body += [rel, _file_facts(p), ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(body), encoding="utf-8")
    return rels


def _dlls(n: int) -> str:
    return f"{n} DLL" if n == 1 else f"{n} DLLs"


def _first_version(dist_root: Path, name: str) -> str:
    """``FileVersion`` of the first ``name`` in the bundle without its trailing ``.0`` ('' if absent)."""
    hit = next(iter(sorted(dist_root.rglob(name))), None)
    ver = pe_version_strings(hit).get("FileVersion", "") if hit else ""
    return ver[:-2] if ver.count(".") == 3 and ver.endswith(".0") else ver


def collect_runtime_licenses(dist_root: Path, found: list[BundledDistribution],
                             python_home: Path | None = None, repo: Path = REPO) -> list[BundledDistribution]:
    """The licences of what the bundle contains besides Python distributions; returns the new rows.

    Why: the distribution metadata covers neither the interpreter nor the binaries the wheels
    carry without a licence file. The release gate of 1 November 2026 found the frozen app
    shipping no LGPL/GPL text for Qt (its wheels hold only ``LicenseRef-Qt-Commercial.txt``), no
    PSF licence for CPython and the OpenSSL, libffi and expat code it contains, and no notice for
    the NVIDIA CUDA/cuDNN and Intel OpenMP libraries in ``torch/lib``. This adds:

    * ``licenses/python/``: ``LICENSE.txt`` and the documentation's ``license.html`` from the
      Python installation the build runs on (``python_home``, default ``sys.base_prefix``), plus
      a README naming the bundled libraries each one covers;
    * ``LGPL-3.0.txt``, ``GPL-3.0.txt`` and a README (licence choice, replacing the DLLs, where
      the source is) in the folder of each bundled Qt for Python distribution;
    * ``licenses/nvidia-cuda/NOTICE.txt`` and ``licenses/intel-openmp/NOTICE.txt``: each bundled
      file with the version and copyright recorded in it, the agreement that governs it and
      where to read that agreement;
    * the licences of the third-party libraries VTK and Qt build into their DLLs
      (:func:`collect_vtk_third_party`, :func:`collect_qt_third_party`).

    The vendored texts are read from ``repo`` (the build's snapshot), like every other input.
    """
    vend = repo / "packaging" / "licenses"
    out_dir = dist_root / "licenses"
    rows: list[BundledDistribution] = []
    versions = {d.name: d.version for d in found}
    home = Path(sys.base_prefix if python_home is None else python_home)
    py_files = []
    for src, name in ((home / "LICENSE.txt", "LICENSE.txt"), (home / "Doc" / "html" / "license.html", "license.html")):
        if src.is_file():
            (out_dir / "python").mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, out_dir / "python" / name)
            py_files.append(f"licenses/python/{name}")
    if py_files:
        import platform
        readme = _fill((vend / "python-runtime.txt").read_text(encoding="utf-8"),
                       python_version=platform.python_version(),
                       sqlite_version=_first_version(dist_root, "sqlite3.dll") or "as bundled")
        (out_dir / "python" / "README.txt").write_text(readme, encoding="utf-8")
        rows.append(BundledDistribution(f"Python (CPython {platform.python_version()})", platform.python_version(),
                                        "PSF-2.0; bundled libraries as listed in python/README.txt",
                                        [*py_files, "licenses/python/README.txt"]))
    qt = [d for d in found if d.name in QT_DISTRIBUTIONS]
    qt_version = _first_version(dist_root, "Qt6Core.dll")
    pyside_version = next((d.version for d in qt if d.name.lower().startswith("pyside6")), "")
    for d in qt:
        folder = out_dir / d.name
        folder.mkdir(parents=True, exist_ok=True)
        for text in ("LGPL-3.0.txt", "GPL-3.0.txt"):
            shutil.copy2(vend / text, folder / text)
            d.files.append(f"licenses/{d.name}/{text}")
        readme = _fill((vend / "qt-for-python.txt").read_text(encoding="utf-8"),
                       pyside_version=pyside_version or d.version, qt_version=qt_version or "as bundled")
        (folder / "README.txt").write_text(readme, encoding="utf-8")
        d.files.append(f"licenses/{d.name}/README.txt")
        d.license = "used under LGPL-3.0-only (texts and source pointers in its folder)"
    torch_version = versions.get("torch", "as bundled")
    nvidia = _runtime_notice(dist_root, out_dir / "nvidia-cuda" / "NOTICE.txt", vend / "nvidia-cuda.txt",
                             NVIDIA_DLL_RE, torch_version=torch_version)
    if nvidia:
        rows.append(BundledDistribution(f"NVIDIA CUDA/cuDNN ({_dlls(len(nvidia))})", "in torch",
                                        "NVIDIA CUDA EULA; cuDNN SLA (see NOTICE.txt)",
                                        ["licenses/nvidia-cuda/NOTICE.txt"]))
    intel = _runtime_notice(dist_root, out_dir / "intel-openmp" / "NOTICE.txt", vend / "intel-openmp.txt",
                            INTEL_OPENMP_RE, torch_version=torch_version)
    if intel:
        rows.append(BundledDistribution(f"Intel OpenMP runtime ({_dlls(len(intel))})", "in torch",
                                        "Intel EULA for Developer Tools (see NOTICE.txt)",
                                        ["licenses/intel-openmp/NOTICE.txt"]))
    rows += collect_vtk_third_party(dist_root, repo)
    rows += collect_qt_third_party(dist_root, found, repo)
    return rows


def _load_components(folder: Path) -> dict:
    return json.loads((folder / "components.json").read_text(encoding="utf-8"))


def _copy_texts(src_root: Path, dst_root: Path, rels: Iterable[str], dist_root: Path) -> list[str]:
    out = []
    for rel in rels:
        dst = dst_root / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src_root / rel, dst)
        out.append(dst.relative_to(dist_root).as_posix())
    return out


def collect_vtk_third_party(dist_root: Path, repo: Path = REPO) -> list[BundledDistribution]:
    """Licences of the third-party libraries VTK bundles as its own DLLs; returns the new row.

    Why: the VTK wheel's ``.dist-info`` holds only VTK's own ``Copyright.txt``, but ``vtk.libs``
    also carries VTK's builds of zlib, libpng, libjpeg-turbo, libtiff, FreeType, expat, lz4,
    liblzma, pugixml, JsonCpp, KISS FFT, Verdict, scnlib, MetaIO, Loguru, glad and {fmt}, whose
    licences require their notices in binary redistributions (release gate 3, 2 November 2026).
    The texts are vendored verbatim from the VTK source tree at the bundled tag
    (``packaging/licenses/vtk``). Every such DLL in the bundle must have an entry: a VTK update that
    adds a vendored library fails the build instead of shipping it without its licence.
    """
    vend = repo / "packaging" / "licenses" / "vtk"
    dlls = sorted({(m.group(1), p) for p in dist_root.rglob("vtk*.dll") if (m := VTK_THIRD_PARTY_RE.match(p.name))})
    if not dlls:
        return []
    manifest = _load_components(vend)
    by_dll = {c["dll"]: c for c in manifest["components"]}
    missing = sorted({key for key, _ in dlls if key not in by_dll})
    if missing:
        raise RuntimeError(f"VTK third-party DLLs without a vendored licence in {vend}: {', '.join(missing)} "
                           "(add them to components.json and UPSTREAM.sha256, see packaging/licenses/README.md)")
    out = dist_root / "licenses" / "vtk" / "third_party"
    present = {key: p for key, p in dlls}
    files, lines = [], []
    for key in sorted(present, key=str.lower):
        c = by_dll[key]
        files += _copy_texts(vend, out, c["files"], dist_root)
        tag = f", upstream {c['upstream_tag']}" if c.get("upstream_tag") else ""
        lines += [f"{c['name']} - {c['description']}",
                  f"    file:     {present[key].relative_to(dist_root).as_posix()}",
                  f"    licence:  {c['license']}",
                  f"    source:   VTK {manifest['version']} {c['upstream']}{tag}",
                  f"    texts:    {', '.join(c['files'])}", ""]
    head = [f"Third-party libraries bundled in VTK {manifest['version']}", "=" * 60, "",
            "VTK (licensed under its own BSD-3-Clause licence, ../LICENSE) builds these libraries into",
            "separate DLLs in _internal/vtk.libs. Each folder here holds the licence text of one of them,",
            "copied verbatim from the VTK source tree:", f"{manifest['source']}", "",
            "Portions of this software are copyright (C) The FreeType Project (www.freetype.org).",
            "All rights reserved.", "This software is based in part on the work of the Independent JPEG Group.",
            "", ""]
    (out / "README.txt").write_text("\n".join(head + lines), encoding="utf-8")
    return [BundledDistribution(f"VTK third-party libraries ({len(present)})", manifest["version"],
                                "as listed in vtk/third_party/README.txt",
                                [*files, "licenses/vtk/third_party/README.txt"])]


def collect_qt_third_party(dist_root: Path, found: list[BundledDistribution],
                           repo: Path = REPO) -> list[BundledDistribution]:
    """Attributions and licences of the third-party code built into the bundled Qt; returns the new row.

    Why: Qt for Python's wheels carry no attribution for the code Qt compiles in (HarfBuzz,
    FreeType, libpng, libjpeg-turbo, libtiff, libwebp, md4c, PCRE2, zlib, double-conversion, the
    Unicode data and more), nor for Mesa's llvmpipe in ``opengl32sw.dll`` (release gate 3,
    2 November 2026). ``packaging/licenses/qt/components.json`` is Qt's own attribution data
    (``qt_attribution.json`` of qtbase, qtimageformats and qtsvg at the bundled tag) without the
    entries for platforms and modules Aerolume does not bundle; their licence files are vendored
    verbatim next to it. The texts go to ``licenses/<Qt for Python>/third_party/`` with an index.
    """
    qt = next((d for d in found if d.name in QT_DISTRIBUTIONS and d.name.lower().startswith("pyside6")), None)
    if qt is None:
        return []
    vend = repo / "packaging" / "licenses" / "qt"
    manifest = _load_components(vend)
    has_mesa = any(dist_root.rglob("opengl32sw.dll"))
    comps = [c for c in manifest["components"] if c["id"] != "mesa-llvmpipe" or has_mesa]
    out = dist_root / "licenses" / qt.name / "third_party"
    rels = sorted({f for c in comps for f in c["files"]})
    files = _copy_texts(vend, out, rels, dist_root)
    lines = [f"Third-party code in Qt {manifest['version']} as bundled with Aerolume", "=" * 60, "",
             "Qt (used under the LGPL-3.0, see README.txt) contains the code below. The entries are Qt's own",
             "attribution data (qt_attribution.json) for the modules and plugins in _internal/PySide6;",
             "each licence text is in this folder at the path given, copied verbatim from Qt's sources:",
             manifest["source"], ""]
    for c in comps:
        lines += [f"{c['name']}" + (f" {c['version']}" if c.get("version") else ""),
                  f"    used:      {c['usage']}", f"    licence:   {c['license']}"]
        lines += [f"    copyright: {cp}" for cp in c.get("copyright", [])[:12]]
        if len(c.get("copyright", [])) > 12:
            lines.append("    copyright: (further holders in the licence text)")
        lines += [f"    texts:     {', '.join(c['files'])}", ""]
    import textwrap
    lines += ["Not applicable to this build (other platforms or Qt modules that are not bundled):",
              *textwrap.wrap("; ".join(manifest.get("not_applicable", [])), 96,
                             initial_indent="    ", subsequent_indent="    "), ""]
    (out / "README.txt").write_text("\n".join(lines), encoding="utf-8")
    files.append(f"licenses/{qt.name}/third_party/README.txt")
    return [BundledDistribution(f"Qt third-party code ({len(comps)})", manifest["version"],
                                f"as listed in {qt.name}/third_party/README.txt", files)]


def collect_licenses(dist_root: Path, top_level_modules: Iterable[str], repo: Path = REPO,
                     python_home: Path | None = None) -> list[BundledDistribution]:
    """Copy the licence files of every distribution whose modules were bundled, then the rest.

    ``top_level_modules`` are the first components of every module in the frozen build (the
    spec writes them to ``bundled_modules.json``). Each distribution's ``LICENSE``/``COPYING``/
    ``NOTICE`` files go to ``licenses/<name>/`` (nested ones keep their folders, see
    :func:`_licence_subpath`), :func:`collect_runtime_licenses` adds CPython, the Qt LGPL texts and
    the NVIDIA and Intel notices, and ``licenses/README.txt`` lists every component with its
    version and licence. Apache-2.0 requires the notices of what we redistribute, and the Qt
    LGPL needs its licence text next to the replaceable Qt DLLs.
    """
    from importlib import metadata
    mods = set(top_level_modules)
    mapping = metadata.packages_distributions()
    names = sorted({d for m in mods for d in mapping.get(m, [])}, key=str.lower)
    out_dir = dist_root / "licenses"
    out_dir.mkdir(parents=True, exist_ok=True)
    found: list[BundledDistribution] = []
    for name in names:
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        meta = dist.metadata
        lic = meta.get("License-Expression") or ""
        if not lic:
            raw = (meta.get("License") or "").strip()
            lic = raw.splitlines()[0][:80] if raw else ""
        if not lic:
            classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License")]
            lic = "; ".join(classifiers)
        copied = []
        for f in dist.files or []:
            posix = str(f).replace("\\", "/")
            if _LICENSE_RE.search(posix) and (".dist-info/" in posix or posix.count("/") <= 1):
                src = Path(dist.locate_file(f))
                if src.is_file():
                    dst = out_dir / name / _licence_subpath(posix)
                    if dst.is_file() and dst.read_bytes() != src.read_bytes():
                        # same name from the package folder and the .dist-info: keep both
                        dst = dst.with_name(posix.replace("/", "-"))
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dst)
                    copied.append(dst.relative_to(dist_root).as_posix())
        found.append(BundledDistribution(name, dist.version, lic or "see licence files", copied))
    mfoil = repo / "third_party" / "mfoil" / "LICENSE"
    if mfoil.is_file():
        (out_dir / "mfoil").mkdir(exist_ok=True)
        shutil.copy2(mfoil, out_dir / "mfoil" / "LICENSE")
        found.append(BundledDistribution("mfoil (vendored, K. Fidkowski)", "vendored", "MIT", ["licenses/mfoil/LICENSE"]))
    runtime = collect_runtime_licenses(dist_root, found, python_home, repo)
    present = {f.split("/")[1] for d in runtime for f in d.files}
    lines = ["Third-party software bundled with Aerolume", "=" * 42, "",
             "Aerolume itself is licensed under the Apache License 2.0 (../LICENSE).",
             "",
             "Python distributions: each folder holds the licence files that distribution ships",
             "(PyTorch's folder also holds the licences of the open-source projects compiled into it,",
             "under torch/third_party).",
             "Qt for Python (PySide6, shiboken6) is used under the LGPL-3.0: the LGPL-3.0 and GPL-3.0",
             "texts, how to replace its DLLs in _internal/PySide6 and where its source is are in",
             "PySide6_Essentials/README.txt.",
             "", "Also bundled, with their licences or notices in these folders:"]
    qt_folder = next((d.name for d in found if d.name in QT_DISTRIBUTIONS and d.name.lower().startswith("pyside6")),
                     "PySide6_Essentials")
    blurbs = {"python": ["  python/        CPython, its standard library and the libraries it contains (OpenSSL,",
                         "                 libffi, expat, bzip2, zlib, libmpdec, SQLite, liblzma), and the",
                         "                 Microsoft C/C++ runtime files that come with it"],
              "nvidia-cuda": ["  nvidia-cuda/   NVIDIA CUDA and cuDNN runtime libraries in _internal/torch/lib",
                              "                 (proprietary; NVIDIA's agreements govern them, see NOTICE.txt)"],
              "intel-openmp": ["  intel-openmp/  Intel OpenMP runtime in _internal/torch/lib (proprietary; see NOTICE.txt)"],
              "vtk": ["  vtk/third_party/  the libraries VTK builds into _internal/vtk.libs (zlib, libpng,",
                      "                 libjpeg-turbo, libtiff, FreeType, expat, lz4, pugixml, JsonCpp, ...)"],
              qt_folder: [f"  {qt_folder}/third_party/  the code built into Qt (HarfBuzz, FreeType, libpng,",
                          "                 libjpeg-turbo, md4c, PCRE2, zlib, ...) and Mesa llvmpipe (opengl32sw.dll)"]}
    for folder, text in blurbs.items():
        if folder in present:
            lines += text
    lines += ["", f"{'Component':32} {'Version':16} Licence", "-" * 78]
    lines += [f"{d.name[:32]:32} {d.version[:16]:16} {d.license}" for d in [*found, *runtime]]
    (out_dir / "README.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [*found, *runtime]


def prune_own_metadata(dist_root: Path, version: str, generated: Path | None = None) -> list[str]:
    """Keep only the generated ``aerolume-<version>.dist-info`` in the app; return what was removed.

    PyInstaller 6 also collects the metadata of every distribution named in a literal
    ``importlib.metadata.version("...")`` call it finds in the bytecode, and the self-test's
    ``_check_metadata`` asks for ``"aerolume"``. For an editable install that pulls in the
    ``.dist-info`` written on the day ``pip install -e`` ran (0.1.0 on the development machine,
    with ``direct_url.json`` naming the developer's OneDrive folder) next to the one
    :func:`write_dist_info` generated. With two folders ``importlib.metadata`` returns whichever
    the directory listing yields first - the old one - so a development build reported an older
    version (caught by the frozen self-test). Removing the extra folders after PyInstaller is
    more reliable than trying to stop every collection path.

    When the editable install's version equals the release's (0.1.0 is both the first release
    and the version the development venv was installed with), both folders have the same name
    and PyInstaller merges them: the kept folder would then also carry the editable install's
    ``RECORD`` and ``direct_url.json`` (the developer's own source path). With ``generated`` (the
    folder :func:`write_dist_info` wrote) the kept folder is replaced by an exact copy of it, and
    each merged-in file name is reported as ``"<folder>/<file>"``.
    """
    internal = dist_root / "_internal"
    keep = f"aerolume-{version}.dist-info"
    if not (internal / keep).is_dir():
        raise FileNotFoundError(f"the generated {keep} is missing from {internal}")
    removed = []
    for d in sorted(internal.glob("aerolume-*.dist-info")):
        if d.name != keep:
            shutil.rmtree(d)
            removed.append(d.name)
    if generated is not None and Path(generated).is_dir():
        own = {p.name for p in Path(generated).iterdir()}
        removed += [f"{keep}/{p.name}" for p in sorted((internal / keep).iterdir()) if p.name not in own]
        shutil.rmtree(internal / keep)
        shutil.copytree(generated, internal / keep)
    return removed


def remove_pycache(root: Path) -> int:
    """Delete ``__pycache__`` folders (stale bytecode from the source tree); returns how many."""
    n = 0
    for d in sorted(root.rglob("__pycache__"), reverse=True):
        shutil.rmtree(d, ignore_errors=True)
        n += 1
    return n


def processes_running_from(folder: Path) -> list[tuple[int, str]]:
    """(pid, executable) of every process whose program file lies inside ``folder`` (Windows).

    Windows refuses to delete a running program's files but happily renames its folder, so the
    only safe test before replacing an app folder is to ask which processes run from it. A
    rebuild started while the app was open from ``dist`` (to try it) used to fail half-way
    through deleting the old folder: its installer was already gone, ``aerolume-cli.exe`` (first
    by name) was deleted and ``Aerolume.exe`` was not, which left a broken folder behind.
    Processes this user may not query (other users', protected ones) cannot be running our build
    and are skipped. Elsewhere than Windows the list is empty (the build is Windows-only).
    """
    if sys.platform != "win32":
        return []
    import ctypes
    from ctypes import wintypes

    psapi, k32 = ctypes.WinDLL("psapi"), ctypes.WinDLL("kernel32")
    k32.OpenProcess.restype = wintypes.HANDLE
    k32.OpenProcess.argtypes = (wintypes.DWORD, wintypes.BOOL, wintypes.DWORD)
    k32.QueryFullProcessImageNameW.argtypes = (wintypes.HANDLE, wintypes.DWORD, wintypes.LPWSTR,
                                               ctypes.POINTER(wintypes.DWORD))
    k32.CloseHandle.argtypes = (wintypes.HANDLE,)
    pids = (wintypes.DWORD * 8192)()
    needed = wintypes.DWORD()
    if not psapi.EnumProcesses(pids, ctypes.sizeof(pids), ctypes.byref(needed)):
        return []
    root = os.path.normcase(str(Path(folder).resolve())).rstrip("\\/") + os.sep
    found: list[tuple[int, str]] = []
    for pid in pids[:needed.value // ctypes.sizeof(wintypes.DWORD)]:
        handle = k32.OpenProcess(0x1000, False, pid)          # PROCESS_QUERY_LIMITED_INFORMATION
        if not handle:
            continue
        try:
            buf = ctypes.create_unicode_buffer(32768)
            size = wintypes.DWORD(len(buf))
            if k32.QueryFullProcessImageNameW(handle, 0, buf, ctypes.byref(size)) \
                    and os.path.normcase(buf.value).startswith(root):
                found.append((int(pid), buf.value))
        finally:
            k32.CloseHandle(handle)
    return found


def dir_stats(root: Path) -> dict[str, int]:
    """Total bytes and file count under ``root``."""
    total = files = 0
    for dirpath, _dirs, names in os.walk(root):
        for n in names:
            with contextlib.suppress(OSError):
                total += os.path.getsize(os.path.join(dirpath, n))
                files += 1
    return {"bytes": total, "files": files}


def largest_files(root: Path, n: int = 12) -> list[tuple[str, int]]:
    """The ``n`` biggest files (relative path, bytes), for the size breakdown in the report."""
    items = []
    for dirpath, _dirs, names in os.walk(root):
        for name in names:
            p = Path(dirpath) / name
            with contextlib.suppress(OSError):
                items.append((p.relative_to(root).as_posix(), p.stat().st_size))
    return sorted(items, key=lambda t: t[1], reverse=True)[:n]


def human(n: float) -> str:
    """Bytes as ``1.23 GB`` (decimal units, as Explorer's 'size' and installers report)."""
    for unit in ("B", "kB", "MB", "GB", "TB"):
        if abs(n) < 1000 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.2f} {unit}"
        n /= 1000.0
    return f"{n:.2f} TB"


