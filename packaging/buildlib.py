def read_version(repo: Path = REPO) -> str:
    """``aerolume.__version__`` read from the source without importing the package."""
    text = (repo / "src" / "aerolume" / "__init__.py").read_text(encoding="utf-8")
    m = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']', text, re.MULTILINE)
    if not m:
        raise RuntimeError("no __version__ in src/aerolume/__init__.py")
    return m.group(1)


def version_quad(version: str) -> tuple[int, int, int, int]:
    """``"0.2.1rc1"`` -> ``(0, 2, 1, 0)``: Windows version resources hold four 16-bit numbers."""
    nums = [int(n) for n in re.findall(r"\d+", version.split("+")[0])[:3]]
    nums += [0] * (4 - len(nums))
    return tuple(min(max(n, 0), 65535) for n in nums[:4])  # type: ignore[return-value]


def version_resource(version: str, variant: str, *, exe_name: str, description: str) -> str:
    """PyInstaller ``version=`` file text (a ``VSVersionInfo`` literal) for one executable."""
    q = version_quad(version)
    strings = {
        "CompanyName": PUBLISHER,
        "FileDescription": description,
        "FileVersion": version,
        "InternalName": Path(exe_name).stem,
        "LegalCopyright": "Copyright Aerolume contributors. Licensed under the Apache License 2.0.",
        "OriginalFilename": exe_name,
        "ProductName": APP_NAME,
        "ProductVersion": f"{version} ({variant.upper()})",
    }
    entries = ",\n          ".join(f"StringStruct({k!r}, {v!r})" for k, v in strings.items())
    return f"""# Generated by packaging/buildlib.py - do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={q}, prodvers={q}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
          {entries}])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


